from abc import ABC, abstractmethod


class LLMError(Exception):
    """Base exception for all LLM provider failures.

    Ensures API keys, auth headers, or raw sensitive requests are never
    included in exception representations or stack trace messages.
    """

    def __init__(self, message: str, provider: str = "unknown"):
        super().__init__(f"[{provider}] {message}")
        self.provider = provider
        self.message = message


class LLMProvider(ABC):
    """Abstract interface for LLM provider wrappers."""

    @abstractmethod
    def generate(self, system_prompt: str, user_prompt: str, *, timeout: float = 15.0) -> str:
        """Generate a response text from the given system and user prompts.

        Args:
            system_prompt: Guiding instructions and constraints for the LLM.
            user_prompt: User query and assembled context.
            timeout: Maximum network duration in seconds (defaults to 15.0s).

        Returns:
            The raw string response generated by the provider.

        Raises:
            LLMError: If any network, timeout, validation, or HTTP error occurs.
        """
        raise NotImplementedError

